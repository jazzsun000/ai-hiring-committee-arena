import { chromium } from 'playwright-core';
const BASE = process.argv[2] || 'http://localhost:5173';
const TAG = process.argv[3] || 'demo';
const OUT = '/workspace/ai-hiring-arena-shots';
const STRONG = "I'd define success as 7-day activation, meaning a user completes their first core action, since that's what predicts retention. I'd run a randomized A/B test at the user level. Assuming a 20% baseline and a 2-point minimum detectable effect, I'd calculate the sample size for 80% power, which is roughly 6-7k users per arm. Guardrails would be support tickets, onboarding drop-off, and day-1 crash rate. I'd check sample ratio mismatch before reading results, avoid peeking by fixing the duration at two full weeks to cover weekday effects, and segment by new vs. returning platform. If it's significant but small, I'd look at whether the lift holds at day 30 before calling it a win.";
const WEAK = "I'd just compare revenue before and after the change. If revenue went up, the pricing worked. Maybe also look at a dashboard to see if users like it.";
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(BASE);
await page.getByTestId('mode-badge').waitFor();
await page.waitForFunction(() => document.querySelector('[data-testid=mode-badge]')?.textContent !== '…');
console.log('badge:', await page.getByTestId('mode-badge').textContent(), '| banner:', await page.getByTestId('demo-banner').count());
await page.screenshot({ path: `${OUT}/${TAG}-01-landing.png`, fullPage: true });
await page.getByTestId('start').click();
await page.getByTestId('answer').waitFor();
const links = page.locator('[data-testid=sources] a');
console.log('telem source links:', await links.count(), '| first:', await links.first().getAttribute('href'), '| target:', await links.first().getAttribute('target'), '| rel:', await links.first().getAttribute('rel'));
console.log('banner text:', await page.getByTestId('demo-banner').innerText().catch(() => '(none)'));
console.log('Q1 bubble includes Telem snippet:', /context \(/.test(await page.locator('.arena-bubble-text').innerText()));
await page.screenshot({ path: `${OUT}/${TAG}-telem-sources.png`, fullPage: true });
console.log('chip R1:', (await page.getByTestId('question-chip').innerText()).replace(/\n/g, ' | '));
await page.screenshot({ path: `${OUT}/${TAG}-02-q1.png`, fullPage: true });
await page.route('**/api/answer', async (r) => { await new Promise((ok) => setTimeout(ok, 1500)); await r.continue(); });
await page.getByTestId('answer').fill(STRONG);
await page.getByTestId('submit').click();
await page.getByTestId('busy').waitFor();
console.log('busy line:', await page.getByTestId('busy').innerText(), '| thinking avatars:', await page.locator('.av--thinking').count());
await page.screenshot({ path: `${OUT}/${TAG}-02b-scoring-thinking.png`, fullPage: true });
await page.getByTestId('score-maya-1').waitFor();
await page.unroute('**/api/answer');
await page.getByTestId('answer').waitFor();
console.log('chip R2:', (await page.getByTestId('question-chip').innerText()).replace(/\n/g, ' | '));
await page.waitForTimeout(700);
console.log('chip opacity R2:', await page.locator('.qchip').evaluate((e) => getComputedStyle(e).opacity));
await page.getByTestId('question-chip').screenshot({ path: `${OUT}/${TAG}-r2-chip-up.png` });
await page.screenshot({ path: `${OUT}/${TAG}-03-q2-after-strong.png`, fullPage: true });
await page.getByTestId('answer').fill(WEAK);
await page.getByTestId('submit').click();
await page.getByTestId('see-scorecard').waitFor();
console.log('R2 scores:', await page.getByTestId('score-maya-2').innerText(), '||', await page.getByTestId('score-alex-2').innerText());
console.log('+1 round visible:', await page.getByTestId('plus-one').isVisible(), '| finish visible:', await page.getByTestId('finish').isVisible());
await page.screenshot({ path: `${OUT}/${TAG}-04-after-weak.png`, fullPage: true });
if (process.env.PLUS_ONE) {
  await page.getByTestId('plus-one').click();
  await page.getByTestId('answer').waitFor();
  console.log('chip R3 (+1 round):', (await page.getByTestId('question-chip').innerText()).replace(/\n/g, ' | '));
  await page.waitForTimeout(700);
  console.log('chip opacity R3:', await page.locator('.qchip').evaluate((e) => getComputedStyle(e).opacity));
  await page.getByTestId('question-chip').screenshot({ path: `${OUT}/${TAG}-r3-chip-down.png` });
  await page.screenshot({ path: `${OUT}/${TAG}-04b-q3-after-weak.png`, fullPage: true });
  const lst = page.locator('.ledger-list');
  console.log('ledger scrolled to bottom:', await lst.evaluate((e) => Math.abs(e.scrollHeight - e.clientHeight - e.scrollTop) < 4 || e.scrollHeight <= e.clientHeight));
  await page.getByTestId('ledger').screenshot({ path: `${OUT}/${TAG}-ledger.png` });
  await page.getByTestId('finish').click();
} else await page.getByTestId('see-scorecard').click();
await page.getByTestId('scorecard').waitFor();
const quotes = await page.locator('[data-testid=quotes] blockquote').allInnerTexts();
console.log('quotes:', quotes);
await page.waitForTimeout(1200);
console.log('scorecard auto-scrolled into view:', await page.getByTestId('scorecard').evaluate((e) => { const r = e.getBoundingClientRect(); return r.top < window.innerHeight && r.bottom > 0; }), '| scrollY:', await page.evaluate(() => window.scrollY));
const ledgerRows = await page.locator('.ledger-row').count();
console.log('ledger rows:', ledgerRows);
await page.getByTestId('bruin-adaptivity').waitFor({ timeout: 60000 });
console.log('bruin panel:', (await page.getByTestId('bruin-panel').innerText()).replace(/\n/g, ' | '));
console.log('bruin pill visible:', await page.getByTestId('bruin-pill').isVisible());
await page.screenshot({ path: `${OUT}/${TAG}-05-scorecard.png`, fullPage: true });
await page.screenshot({ path: `${OUT}/${TAG}-scorecard-viewport.png` });
// restart without reload
await page.getByTestId('restart').click();
console.log('restart -> start button visible:', await page.getByTestId('start').isVisible());
console.log('console errors:', errors.length ? errors : 'none');
await browser.close();

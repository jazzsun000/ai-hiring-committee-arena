import { chromium } from 'playwright-core';
const U = process.argv[2], STRONG = process.argv[3];
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1' });
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
const r = await p.goto(U); console.log('homepage', r.status());
await p.getByTestId('mode-badge').filter({ hasText: 'LIVE' }).waitFor({ timeout: 30000 });
console.log('badge', await p.getByTestId('mode-badge').innerText());
console.log('voice-toggle present', await p.getByTestId('voice-toggle').count());
await p.getByTestId('voice-toggle').click(); console.log('voice toggle after tap:', await p.getByTestId('voice-toggle').innerText());
await p.selectOption('select >> nth=0', 'Netflix').catch(() => console.log('(no company select)'));
await p.getByRole('button', { name: /start/i }).first().click();
await p.getByTestId('answer').waitFor({ timeout: 60000 });
const q = await p.locator('.bubble, [class*=bubble]').first().innerText().catch(() => '');
console.log('Q1 bubble:', q);
console.log('mid-sentence ellipsis in Q1:', /(\.\.\.|…)/.test(q));
console.log('mic present', await p.getByTestId('mic').count());
const TAG = process.env.SHOT_TAG || 'v2';
console.log('replay buttons (bubble, question card):', await p.getByTestId('replay-bubble').count(), await p.getByTestId('replay-q-1').count());
await p.evaluate(() => window.scrollTo(0, 0));
const geo = await p.evaluate(() => { const a = document.querySelector('.arena')?.getBoundingClientRect(); const b = document.querySelector('.arena-bubble')?.getBoundingClientRect(); const t = document.querySelector('.arena-bubble-text'); return { arenaTop: a?.top, bubbleTop: b?.top, scrollTop: t?.scrollTop, start: (t?.textContent || '').slice(0, 40) }; });
console.log('bubble geometry', JSON.stringify(geo), 'bubble start visible:', geo.bubbleTop >= geo.arenaTop && geo.scrollTop === 0);
await p.screenshot({ path: `/workspace/ai-hiring-arena-shots/lingcode-voice-mobile-${TAG}.png` });
await p.getByTestId('answer').fill(STRONG); await p.getByTestId('submit').click();
await p.getByTestId('answer').waitFor({ timeout: 90000 });
await p.getByTestId('answer').fill("I'd just compare revenue before and after the change."); await p.getByTestId('submit').click();
await p.getByTestId('see-scorecard').click({ timeout: 90000 });
await p.getByText(/Recommendation/i).first().waitFor({ timeout: 90000 });
console.log('scorecard shown; quotes:', await p.locator('q').count());
await p.screenshot({ path: `/workspace/ai-hiring-arena-shots/lingcode-voice-mobile-scorecard-${TAG}.png` });
console.log('page errors', errs.length, errs.slice(0, 2));
await b.close();
